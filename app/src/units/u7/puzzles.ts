const r = Math.SQRT1_2;
const h = 0.5;
const s8 = 1 / Math.sqrt(8);

/** Amplitude list helper: basis-index → [re, im]; everything else 0. */
function amps(n: number, entries: Record<number, [number, number]>): [number, number][] {
  return Array.from({ length: 1 << n }, (_, i) => entries[i] ?? [0, 0]);
}
const e = (theta: number, mag = r): [number, number] => [mag * Math.cos(theta), mag * Math.sin(theta)];

const BELL_PHI_PLUS = amps(2, { 0: [r, 0], 3: [r, 0] });
const BELL_PSI_MINUS = amps(2, { 1: [r, 0], 2: [-r, 0] });
const GHZ3 = amps(3, { 0: [r, 0], 7: [r, 0] });

/** |a b c⟩ with every qubit in |+⟩ except the listed ones in |−⟩ (product of ± states). */
function plusMinus(n: number, minus: number[]): [number, number][] {
  return Array.from({ length: 1 << n }, (_, x) => {
    let sign = 1;
    for (const q of minus) if ((x >> (n - 1 - q)) & 1) sign = -sign;
    return [sign / Math.sqrt(1 << n), 0] as [number, number];
  });
}

