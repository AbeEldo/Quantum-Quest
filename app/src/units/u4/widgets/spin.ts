/**
 * Small spin-½ toolkit for World 4 widgets & games.
 *
 * Conventions (ħ = 1):
 *   Bloch vector r = (⟨σx⟩, ⟨σy⟩, ⟨σz⟩).
 *   H = (ω/2) n̂·σ  ⇒  U(t) = exp(−iHt) rotates r about n̂ by angle ωt (right-hand rule).
 *   Rotating-frame drive Hamiltonian:  H = (Δ/2) σz + (Ω/2)(cos φ σx + sin φ σy)
 *   (Δ = ω_qubit − ω_drive is the detuning, Ω the Rabi frequency, φ the drive phase).
 */
import { c, type C, fmt } from '../../../engine/complex';

export type V3 = [number, number, number];

export const dot = (a: V3, b: V3) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
export const cross = (a: V3, b: V3): V3 => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];
export const norm = (a: V3) => Math.hypot(a[0], a[1], a[2]);
export const normalize = (a: V3): V3 => {
  const n = norm(a) || 1;
  return [a[0] / n, a[1] / n, a[2] / n];
};
export const scale3 = (a: V3, s: number): V3 => [a[0] * s, a[1] * s, a[2] * s];

/** Rodrigues rotation of v about (not necessarily unit) axis n by angle a. */
export function rot(v: V3, n: V3, a: number): V3 {
  const k = normalize(n);
  const co = Math.cos(a), si = Math.sin(a);
  const d = dot(k, v);
  const x = cross(k, v);
  return [v[0] * co + x[0] * si + k[0] * d * (1 - co), v[1] * co + x[1] * si + k[1] * d * (1 - co), v[2] * co + x[2] * si + k[2] * d * (1 - co)];
}

export interface Pulse {
  /** Rabi frequency (rad per time unit). 0 = free evolution. */
  omega: number;
  /** Drive phase φ in radians (0 → x axis, π/2 → y axis). */
  phase: number;
  /** Detuning Δ (rad per time unit). */
  detuning: number;
  /** Duration. */
  duration: number;
}

/** Axis (unit) and angular rate of the rotation generated by a pulse in the rotating frame. */
export function pulseAxis(omega: number, phase: number, detuning: number): { axis: V3; rate: number } {
  const v: V3 = [omega * Math.cos(phase), omega * Math.sin(phase), detuning];
  const rate = norm(v);
  return { axis: rate > 1e-12 ? scale3(v, 1 / rate) : [0, 0, 1], rate };
}

/** Bloch vector after applying a pulse for time t (exact). */
export function applyPulse(v: V3, p: Pulse, t = p.duration, extraDetuning = 0): V3 {
  const { axis, rate } = pulseAxis(p.omega, p.phase, p.detuning + extraDetuning);
  return rot(v, axis, rate * t);
}

/** Apply a whole sequence of pulses. */
export function applySequence(v: V3, seq: Pulse[], extraDetuning = 0): V3 {
  let r = v;
  for (const p of seq) r = applyPulse(r, p, p.duration, extraDetuning);
  return r;
}

/** Rabi formula: probability of |1⟩ starting from |0⟩. */
export function rabiP1(omega: number, detuning: number, t: number) {
  const W = Math.hypot(omega, detuning);
  if (W < 1e-12) return 0;
  return ((omega * omega) / (W * W)) * Math.sin((W * t) / 2) ** 2;
}

/** Fidelity |⟨a|b⟩|² between two pure states given by Bloch vectors. */
export const blochFidelity = (a: V3, b: V3) => (1 + dot(a, b)) / 2;

/** Bloch vector → amplitudes (α real ≥ 0). */
export function blochToKet(r: V3): [C, C] {
  const n = normalize(r);
  const theta = Math.acos(Math.max(-1, Math.min(1, n[2])));
  const phi = Math.atan2(n[1], n[0]);
  return [c(Math.cos(theta / 2)), c(Math.sin(theta / 2) * Math.cos(phi), Math.sin(theta / 2) * Math.sin(phi))];
}

/** n̂·σ as a 2×2 complex matrix. */
export function nDotSigma(n: V3): C[][] {
  return [
    [c(n[2]), c(n[0], -n[1])],
    [c(n[0], n[1]), c(-n[2])],
  ];
}

/** TeX for a complex number (compact). */
export function texC(z: C, digits = 2): string {
  return fmt(z, digits).replace(/−/g, '-');
}

/** TeX for a small complex matrix. */
export function texMat(m: C[][], digits = 2): string {
  return '\\begin{pmatrix}' + m.map((row) => row.map((z) => texC(z, digits)).join(' & ')).join('\\\\') + '\\end{pmatrix}';
}

/** TeX for a column vector. */
export function texVec(v: C[], digits = 3): string {
  return '\\begin{pmatrix}' + v.map((z) => texC(z, digits)).join('\\\\') + '\\end{pmatrix}';
}

/** Ease in-out for animations. */
export const ease = (t: number) => (t < 0.5 ? 4 * t * t * t : 1 - Math.pow(-2 * t + 2, 3) / 2);
